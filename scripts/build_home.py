#!/usr/bin/env python3
"""Build the deterministic research-metrics fragment used by the homepage."""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "data" / "research-metrics.json"
OUTPUT = ROOT / "home" / "_metrics.md"


def load_metrics() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    required = {"updated_at", "orcid", "public_orcid_works", "openalex"}
    missing = required - data.keys()
    if missing:
        raise ValueError(f"research-metrics.json missing fields: {sorted(missing)}")
    return data


def format_date(value: str) -> str:
    return datetime.fromisoformat(value.replace("Z", "+00:00")).strftime("%d %b %Y")


def render(data: dict) -> str:
    oa = data["openalex"]
    updated = format_date(data["updated_at"])
    metrics = [
        (data["public_orcid_works"], "ORCID works"),
        (oa.get("works_count", 0), "OpenAlex works"),
        (oa.get("cited_by_count", 0), "Citations"),
        (oa.get("h_index", 0), "h-index"),
        (oa.get("i10_index", 0), "i10-index"),
    ]

    cards = []
    for value, label in metrics:
        cards.append(
            '<div class="qs-metric-card">\n'
            f'<span class="qs-metric-value">{value}</span>\n'
            f'<span class="qs-metric-label">{label}</span>\n'
            '</div>'
        )

    return (
        "```{=html}\n"
        "<!-- Generated by scripts/build_home.py. Do not edit manually. -->\n"
        '<section class="qs-metrics-block" aria-label="Research metrics">\n'
        '<div class="qs-metrics-grid">\n'
        + "\n".join(cards)
        + "\n</div>\n"
        '<p class="qs-metrics-note">\n'
        f"Public scholarly record from ORCID and OpenAlex · updated {updated}. Citation metrics are\n"
        "automatically refreshed from OpenAlex; Google Scholar is linked for discovery but is not scraped.\n"
        "</p>\n"
        "</section>\n"
        "```\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if the generated fragment is stale.")
    args = parser.parse_args()

    expected = render(load_metrics())

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != expected:
            raise SystemExit("home/_metrics.md is stale; run python scripts/build_home.py")
        print("Homepage metrics fragment is current.")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
